using System.Globalization;
using System.Text;
using System.Text.RegularExpressions;

namespace VehicleVision.PleasanterTools.CalendarStyleCreator;

/// <summary>色の指定。背景色は日曜・祝日と土曜、文字色は日付の数字に使う。#rgb / #rrggbb / #rrggbbaa または英字の色名のみ。</summary>
public sealed record CalendarTheme(string HolidayBackground = "#fff0f3", string SaturdayBackground = "#e8f3ff", string HolidayText = "#b00020", string SaturdayText = "#1565c0")
{
    private static readonly Regex ColorPattern = new("^(#[0-9a-fA-F]{3,8}|[a-zA-Z]{3,30})$", RegexOptions.Compiled);

    public CalendarTheme Validate()
    {
        foreach (var color in new[] { HolidayBackground, SaturdayBackground, HolidayText, SaturdayText })
            if (!ColorPattern.IsMatch(color)) throw new UserError("Color must be like #fff0f3 or a color name.");
        return this;
    }
}

/// <summary>
/// 休日と週末から拡張スタイル用 CSS を作る。標準カレンダーと FullCalendar の両方を 1 つの CSS に出す。
/// 同じ入力から常に同じ出力（日付順・重複日は後勝ち）。優先順位は記述順で、土曜 → 日曜・祝日の順に後勝ちにする（土曜の祝日は祝日の色）。
/// 前月・翌月のはみ出し日は色を付けない（標準は .other-month、FullCalendar は .fc-day-other）。
/// </summary>
/// <remarks>
/// 標準カレンダー（本体 HtmlCalendar.cs と実機で確認）: 本体は <c>#CalendarBody</c> 配下の <c>td.container</c> が <c>data-id="yyyy/M/d"</c>（0 埋めなし）を持つ。
/// 月表示は内側に <c>.day</c>、週表示は <c>td.is-weekly</c>。年表示も同じ td.container で data-id が月初日になるため、<c>:has(&gt; div &gt; .day)</c> で月表示に限定する。
/// セルに曜日クラスがなく、週の開始曜日も設定で変わるため、土日は日付ごとに指定する（対象は fromYear〜toYear の範囲）。
/// FullCalendar（実機 Pleasanter 1.5.8.1 で確認、_development/検証記録.md）: ルートは <c>div#FullCalendar.calendar-container.fc</c>。曜日は <c>.fc-day-sat</c> / <c>.fc-day-sun</c>、
/// 前月・翌月は <c>.fc-day-other</c>、日付は <c>data-date="yyyy-MM-dd"</c>（月・週・日の日セルと見出し th、リストの <c>tr.fc-list-day</c>）。月表示の祝日名は <c>.fc-daygrid-day-top::after</c>。
/// 本体の既定スタイルは <c>#CalendarBody td</c>・<c>#FullCalendar td</c> と ID セレクターで背景を指定するため、<c>:is(#ID, [id^=...])</c> で詳細度を合わせる。
/// </remarks>
public static class CssGenerator
{
    // 本体の既定スタイルは #CalendarBody td・#FullCalendar td（ID セレクター）で背景を指定する。
    // :is(#ID, [id^=...]) は ID 1 つ分の詳細度になるため、!important なしで上書きできる。接尾辞付き ID（ダッシュボード用）にも前方一致するが、ダッシュボードでの表示は未検証。
    private const string Standard = ":is(#CalendarBody, [id^=\"CalendarBody\"])";
    private const string Full = ":is(#FullCalendar, [id^=\"FullCalendar\"]).calendar-container";

    public static string Generate(IEnumerable<Holiday> holidays, CalendarTheme theme, int fromYear, int toYear)
    {
        theme.Validate();
        var byDate = new SortedDictionary<DateOnly, string>();
        foreach (var holiday in holidays) byDate[holiday.Date] = holiday.Name;
        var saturdays = new List<DateOnly>();
        var offDays = new SortedSet<DateOnly>(byDate.Keys);
        for (var day = new DateOnly(fromYear, 1, 1); day <= new DateOnly(toYear, 12, 31); day = day.AddDays(1))
        {
            if (day.DayOfWeek == DayOfWeek.Saturday) saturdays.Add(day);
            else if (day.DayOfWeek == DayOfWeek.Sunday) offDays.Add(day);
        }

        var css = new StringBuilder("/* Generated by CalendarStyleCreator. Do not edit. */\n");
        void Rule(IEnumerable<string> selectors, string declarations)
        {
            var list = selectors.ToList();
            if (list.Count > 0) css.Append(string.Join(",\n", list)).Append(" { ").Append(declarations).Append(" }\n");
        }
        void Day(string weekday, string background, string text, IEnumerable<DateOnly> dates)
        {
            var list = dates.ToList();
            // 曜日クラスは FullCalendar のみ。標準カレンダーは日付ごとに指定する。
            Rule([$"{Full} .fc-day-{weekday}:not(.fc-day-other)"], $"background-color: {background};");
            Rule([$"{Full} .fc-day-{weekday}:not(.fc-day-other) .fc-daygrid-day-number", $"{Full} .fc-day-{weekday}:not(.fc-day-other) .fc-col-header-cell-cushion"], $"color: {text};");
            Rule(list.SelectMany(StandardCell), $"background-color: {background};");
            Rule(list.Select(d => MonthlyCell(d) + " .day"), $"color: {text};");
        }

        Day("sat", theme.SaturdayBackground, theme.SaturdayText, saturdays);
        // 日曜と祝日は同じ色。祝日は日付指定で FullCalendar の曜日クラスより後に置く。
        Day("sun", theme.HolidayBackground, theme.HolidayText, offDays);
        Rule(byDate.Keys.SelectMany(FullCalendarCell), $"background-color: {theme.HolidayBackground};");
        Rule(byDate.Keys.Select(d => $"{Full} td.fc-daygrid-day[data-date=\"{FullCalendarDate(d)}\"]:not(.fc-day-other) .fc-daygrid-day-number"), $"color: {theme.HolidayText};");
        // 週・日表示の見出し（th）は本体の既定が白文字のため、祝日が平日でも文字色を変える（背景は上の th[data-date] ルール）。
        Rule(byDate.Keys.Select(d => $"{Full} th.fc-col-header-cell[data-date=\"{FullCalendarDate(d)}\"] .fc-col-header-cell-cushion"), $"color: {theme.HolidayText};");

        // 標準カレンダーの .day は 24px 幅の中央寄せなので、祝日名を足すと数字に重なる。名称のある祝日は幅を自動にして数字の右に並べる。
        Rule(byDate.Where(h => h.Value.Length > 0).Select(h => MonthlyCell(h.Key) + " .day"), "width: auto; min-width: 24px; padding: 0 4px; justify-content: flex-start;");
        foreach (var (date, name) in byDate)
        {
            if (name.Length == 0) continue;
            var label = $"content: \"{EscapeString(name)}\"; margin-left: 0.5em; font-size: 0.85em; font-weight: 600; white-space: nowrap;";
            var attribute = $"[data-date=\"{FullCalendarDate(date)}\"]";
            Rule([MonthlyCell(date) + " .day::after"], label);
            Rule([$"{Full} td.fc-daygrid-day{attribute}:not(.fc-day-other) .fc-daygrid-day-top::after", $"{Full} th.fc-col-header-cell{attribute} .fc-col-header-cell-cushion::after", $"{Full} .fc-list-day{attribute} .fc-list-day-text::after"], label);
        }
        return css.ToString();
    }

    private static string FullCalendarDate(DateOnly date) => date.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture);

    private static string DataId(DateOnly date) => $"[data-id=\"{date.Year}/{date.Month}/{date.Day}\"]";

    private static string MonthlyCell(DateOnly date) => $"{Standard} td.container:has(> div > .day){DataId(date)}:not(.other-month)";

    /// <summary>標準カレンダーの月表示・週表示のセル。年表示のセルは含めない。</summary>
    private static IEnumerable<string> StandardCell(DateOnly date)
    {
        yield return MonthlyCell(date);
        yield return $"{Standard} td.container.is-weekly{DataId(date)}:not(.other-month)";
    }

    /// <summary>FullCalendar の日セルと、日・週表示の見出し。</summary>
    private static IEnumerable<string> FullCalendarCell(DateOnly date)
    {
        var attribute = $"[data-date=\"{FullCalendarDate(date)}\"]";
        yield return $"{Full} td{attribute}:not(.fc-day-other)";
        yield return $"{Full} th{attribute}";
    }

    /// <summary>CSS 文字列リテラル（二重引用符）用のエスケープ。制御文字は空白、非 ASCII はそのまま残す。</summary>
    public static string EscapeString(string value)
    {
        var escaped = new StringBuilder();
        foreach (var c in value)
        {
            if (c is '"' or '\\') escaped.Append('\\').Append(c);
            else if (c is '<' or '>' or '&') escaped.Append('\\').Append(((int)c).ToString("x", CultureInfo.InvariantCulture)).Append(' ');
            else if (char.IsControl(c)) escaped.Append(' ');
            else escaped.Append(c);
        }
        return escaped.ToString();
    }
}
