using System.Globalization;
using System.Text;
using System.Text.RegularExpressions;

namespace VehicleVision.PleasanterTools.CalendarStyleCreator;

/// <summary>色の指定。背景色は日曜・祝日と土曜と平日、文字色は日付の数字に使う。平日は土日の色を打ち消すための色（既定は背景なし・文字色は継承）。#rgb / #rrggbb / #rrggbbaa または英字の色名のみ。</summary>
public sealed record CalendarTheme(string HolidayBackground = "#fff0f3", string SaturdayBackground = "#e8f3ff", string HolidayText = "#b00020", string SaturdayText = "#1565c0", string WeekdayBackground = "transparent", string WeekdayText = "inherit")
{
    private static readonly Regex ColorPattern = new("^(#[0-9a-fA-F]{3,8}|[a-zA-Z]{3,30})$", RegexOptions.Compiled);

    public CalendarTheme Validate()
    {
        foreach (var color in new[] { HolidayBackground, SaturdayBackground, HolidayText, SaturdayText, WeekdayBackground, WeekdayText })
        {
            if (!ColorPattern.IsMatch(color))
            {
                throw new UserError("Color must be like #fff0f3 or a color name.");
            }
        }

        return this;
    }
}

/// <summary>
/// 休日と週末から拡張スタイル用 CSS を作る。標準カレンダーと FullCalendar の両方を 1 つの CSS に出す。
/// 同じ入力から常に同じ出力（日付順・重複日は後勝ち）。優先順位は記述順で、土曜 → 日曜・祝日の順に後勝ちにする（土曜の祝日は祝日の色）。
/// 前月・翌月のはみ出し日は色を付けない（標準は .other-month、FullCalendar は .fc-day-other）。
/// </summary>
/// <remarks>
/// 標準カレンダー（本体 HtmlCalendar.cs と実機で確認）: 本体は <c>#CalendarBody</c> 配下の <c>td.container</c> が <c>data-id="yyyy/M/d"</c>（0 埋めなし）を持つ。
/// 月表示は内側に <c>.day</c>、週表示は <c>td.is-weekly</c>。年表示も同じ td.container で data-id が月初日になるため、<c>:has(&gt; div &gt; .day)</c> で月表示に限定する。
/// セルに曜日クラスがなく、週の開始曜日も設定で変わるため、土日は日付ごとに指定する（対象は fromYear〜toYear の範囲）。
/// FullCalendar（実機 Pleasanter 1.5.8.1 で確認、_development/検証記録.md）: ルートは <c>div#FullCalendar.calendar-container.fc</c>。曜日は <c>.fc-day-sat</c> / <c>.fc-day-sun</c>、
/// 前月・翌月は <c>.fc-day-other</c>、日付は <c>data-date="yyyy-MM-dd"</c>（月・週・日の日セルと見出し th、リストの <c>tr.fc-list-day</c>）。月表示の祝日名は <c>.fc-daygrid-day-top::after</c>。
/// 本体の既定スタイルは <c>#CalendarBody td</c>・<c>#FullCalendar td</c> と ID セレクターで背景を指定するため、<c>:is(#ID, [id^=...])</c> で詳細度を合わせる。
/// </remarks>
public static class CssGenerator
{
    // 本体の既定スタイルは #CalendarBody td・#FullCalendar td（ID セレクター）で背景を指定する。
    // :is(#ID, [id^=...]) は ID 1 つ分の詳細度になるため、!important なしで上書きできる。接尾辞付き ID（ダッシュボード用）にも前方一致するが、ダッシュボードでの表示は未検証。
    private const string Standard = ":is(#CalendarBody, [id^=\"CalendarBody\"])";
    private const string Full = ":is(#FullCalendar, [id^=\"FullCalendar\"]).calendar-container";

    /// <summary>
    /// 年に依存しない共通部（Core）と、年ごとの CSS。年を跨いで差し替えるのは年ごとのファイルだけで、共通部は変わらない。
    /// 共通部は FullCalendar の曜日クラス（.fc-day-sat / .fc-day-sun）の色。年ごとの祝日の日付指定が、記述順に頼らず詳細度で上書きできるよう、
    /// 共通部のはみ出し日の除外は :where() で詳細度を持たせない（API 登録の拡張は読み込み順を保証できないため）。
    /// </summary>
    /// <summary>週の開始曜日の既定（0=日曜 … 6=土曜）。本体の General.json の FirstDayOfWeek の既定と同じ月曜。</summary>
    public const int DefaultFirstDayOfWeek = 1;

    public sealed record GeneratedStyles(string Core, IReadOnlyDictionary<int, string> Years);

    public static GeneratedStyles Generate(IEnumerable<Holiday> holidays, CalendarTheme theme, int fromYear, int toYear, int firstDayOfWeek = DefaultFirstDayOfWeek)
    {
        theme.Validate();
        if (firstDayOfWeek is < 0 or > 6)
        {
            throw new UserError("First day of week must be 0 (Sunday) to 6 (Saturday).");
        }

        var resolved = DayResolver.Resolve(holidays);
        var years = new SortedDictionary<int, string>();
        for (var year = fromYear; year <= toYear; year++)
        {
            years[year] = Year(year, resolved.Where(h => h.Key.Year == year).ToDictionary(h => h.Key, h => h.Value), theme);
        }

        return new GeneratedStyles(Core(theme, firstDayOfWeek), years);
    }

    private static string Core(CalendarTheme theme, int firstDayOfWeek)
    {
        var css = new StringBuilder("/* Generated by CalendarStyleCreator. Do not edit. */\n/* Core: weekend colors (FullCalendar by weekday class; standard calendar by column position for the configured first day of the week). Holidays are in the per-year styles. */\n");
        foreach (var (weekday, dayOfWeek, background, text) in new[] { ("sat", 6, theme.SaturdayBackground, theme.SaturdayText), ("sun", 0, theme.HolidayBackground, theme.HolidayText) })
        {
            css.Append($"{Full} .fc-day-{weekday}:where(:not(.fc-day-other)) {{ background-color: {background}; }}\n");
            css.Append($"{Full} .fc-day-{weekday}:where(:not(.fc-day-other)) .fc-daygrid-day-number,\n{Full} .fc-day-{weekday}:where(:not(.fc-day-other)) .fc-col-header-cell-cushion {{ color: {text}; }}\n");
            // 標準カレンダーのセルには曜日クラスがないため、列の位置（週の開始曜日からの並び）で指定する。
            // 週の行には th（グループ見出し）が混ざることがあるので、td だけを数える :nth-of-type を使う。
            // 構造の条件は :where() で詳細度を持たせず、年ごとの祝日の日付指定（読み込み順に依らず）が勝つようにする。
            var column = (dayOfWeek - firstDayOfWeek + 7) % 7 + 1;
            var monthly = $"{Standard} td.container:where(:has(> div > .day)):where(:nth-of-type({column})):where(:not(.other-month))";
            var weekly = $"{Standard} td.container.is-weekly:where(:nth-of-type({column}))";
            css.Append($"{monthly},\n{weekly} {{ background-color: {background}; }}\n");
            css.Append($"{monthly} .day {{ color: {text}; }}\n");
        }
        return css.ToString();
    }

    private static (string Background, string Text) Colors(DayType type, CalendarTheme theme) => type switch
    {
        DayType.Holiday => (theme.HolidayBackground, theme.HolidayText),
        DayType.Saturday => (theme.SaturdayBackground, theme.SaturdayText),
        _ => (theme.WeekdayBackground, theme.WeekdayText),
    };

    private static string Year(int year, Dictionary<DateOnly, Holiday> days, CalendarTheme theme)
    {
        var css = new StringBuilder($"/* Generated by CalendarStyleCreator. Do not edit. */\n/* {year}: dates with a day type (holiday / Saturday / weekday), their names, and the FullCalendar list view. Weekend colors are in the core style. */\n");
        void Rule(IEnumerable<string> selectors, string declarations)
        {
            var list = selectors.ToList();
            if (list.Count > 0)
            {
                css.Append(string.Join(",\n", list)).Append(" { ").Append(declarations).Append(" }\n");
            }
        }
        // 日付ごとの色は日祝・土・平日の 3 種類。1 日には最も優先順位の高い種類だけが残っている（DayResolver）。
        // 土日の色（Core）は構造の条件に :where() を使い詳細度が低いので、読み込み順に依らず日付ごとの指定が勝つ。
        // 同じ宣言の日付は :is() で 1 つの規則にまとめ、セレクターの前半の繰り返しを避けてサイズを抑える（:is() の詳細度は引数の最大で、1 日分のときと同じ）。
        foreach (var type in new[] { DayType.Holiday, DayType.Saturday, DayType.Weekday })
        {
            var dates = days.Values.Where(d => d.Type == type).Select(d => d.Date).OrderBy(d => d).ToList();
            if (dates.Count == 0)
            {
                continue;
            }

            var (background, text) = Colors(type, theme);
            Rule([MonthlyOrWeeklyIs(dates)], $"background-color: {background};");
            Rule([MonthlyIs(dates) + " .day"], $"color: {text};");
            // FullCalendar。曜日クラス（Core）より詳細度が高いので、土日の列にある日も指定した種類の色になる。
            Rule([$"{Full} td{FullIs(dates)}:not(.fc-day-other)"], $"background-color: {background};");
            Rule([$"{Full} td.fc-daygrid-day{FullIs(dates)}:not(.fc-day-other) .fc-daygrid-day-number"], $"color: {text};");
            // 週・日表示の見出し（th）。本体の既定は青地に白文字なので、日祝・土の色（背景と文字色）をそのまま付ける。
            // 平日は「打ち消す」色（透明）にすると見出しの青地まで消えて読めなくなるため、見出しには付けない（日の中身のセルだけ打ち消す）。
            if (type != DayType.Weekday)
            {
                Rule([$"{Full} th{FullIs(dates)}"], $"background-color: {background};");
                Rule([$"{Full} th.fc-col-header-cell{FullIs(dates)} .fc-col-header-cell-cushion"], $"color: {text};");
            }
        }

        // FullCalendar のリスト表示。日の行（tr.fc-list-day）には曜日クラスがないため、土日も日付で指定する（Core では指定できない）。
        var listTypes = new Dictionary<DateOnly, DayType>();
        for (var day = new DateOnly(year, 1, 1); day.Year == year; day = day.AddDays(1))
        {
            // 平日は「打ち消す」色（透明）にすると日の見出しの地の色が出てしまうため、リストでは何も付けず本体の既定のままにする。
            if (days.TryGetValue(day, out var entry)) { if (entry.Type != DayType.Weekday)
                {
                    listTypes[day] = entry.Type;
                }
            }
            else if (day.DayOfWeek == DayOfWeek.Saturday)
            {
                listTypes[day] = DayType.Saturday;
            }
            else if (day.DayOfWeek == DayOfWeek.Sunday)
            {
                listTypes[day] = DayType.Holiday;
            }
        }
        foreach (var type in new[] { DayType.Holiday, DayType.Saturday, DayType.Weekday })
        {
            var dates = listTypes.Where(p => p.Value == type).Select(p => p.Key).OrderBy(d => d).ToList();
            if (dates.Count == 0)
            {
                continue;
            }

            var (background, text) = Colors(type, theme);
            Rule([$"{Full} tr.fc-list-day{FullIs(dates)} .fc-list-day-cushion"], $"background-color: {background};");
            Rule([$"{Full} tr.fc-list-day{FullIs(dates)} :is(.fc-list-day-text, .fc-list-day-side-text)"], $"color: {text};");
        }

        var named = days.Values.Where(d => d.Name.Length > 0).OrderBy(d => d.Date).ToList();
        // 標準カレンダーの .day は 24px 幅の中央寄せなので、名称を足すと数字に重なる。名称のある日は幅を自動にして数字の右に並べる。
        Rule([MonthlyIs(named.Select(d => d.Date)) + " .day"], "width: auto; min-width: 24px; padding: 0 4px; justify-content: flex-start;");
        Rule([WeeklyIs(named.Select(d => d.Date))], "position: relative;");
        foreach (var entry in named)
        {
            var date = entry.Date;
            var (background, text) = Colors(entry.Type, theme);
            var label = $"content: \"{EscapeString(entry.Name)}\"; margin-left: 0.5em; font-size: 0.85em; font-weight: 600; white-space: nowrap;";
            var attribute = $"[data-date=\"{FullCalendarDate(date)}\"]";
            Rule([$"{Standard} td.container{DataId(date)}:not(.other-month) .day::after"], label);
            // 標準カレンダーの週表示のセルには日付の数字（.day）がない。名称はセルの流れに入れず（入れると、その日だけ予定が下がり、日をまたぐ予定のバーがずれる）、
            // セルの右上へ絶対配置で重ねる（予定のバーより手前に出し、読めるようにセルと同じ背景を敷く）。
            Rule([WeeklyCell(date) + "::before"], label + $" position: absolute; z-index: 1; right: 0.4em; top: 0.25em; margin: 0; padding: 0 0.25em; border-radius: 3px; background-color: {background}; pointer-events: none; color: {text};");
            // 月表示の .fc-daygrid-day-top は flex の row-reverse（数字が右、名称が左）。数字は上下に余白を持つため、名称も縦中央に揃える。
            Rule([$"{Full} td.fc-daygrid-day{attribute}:not(.fc-day-other) .fc-daygrid-day-top::after"], label + " margin-left: 0; margin-right: 0.25em; align-self: center;");
            Rule([$"{Full} th.fc-col-header-cell{attribute} .fc-col-header-cell-cushion::after", $"{Full} .fc-list-day{attribute} .fc-list-day-text::after"], label);
        }
        return css.ToString();
    }

    private static string FullCalendarDate(DateOnly date) => date.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture);

    private static string DataId(DateOnly date) => $"[data-id=\"{date.Year}/{date.Month}/{date.Day}\"]";

    private static string FullIs(IEnumerable<DateOnly> dates) => ":is(" + string.Join(",", dates.Select(d => $"[data-date=\"{FullCalendarDate(d)}\"]")) + ")";

    private static string StandardIs(IEnumerable<DateOnly> dates) => ":is(" + string.Join(",", dates.Select(DataId)) + ")";

    private static string MonthlyIs(IEnumerable<DateOnly> dates) => $"{Standard} td.container:has(> div > .day){StandardIs(dates)}:not(.other-month)";

    // 週表示では、表示中の 7 日すべてが見える日なので、月をまたぐ日（.other-month）にも色を付ける。
    private static string WeeklyIs(IEnumerable<DateOnly> dates) => $"{Standard} td.container.is-weekly{StandardIs(dates)}";

    // 月表示と週表示のセルを 1 つの選択子にまとめる（日付の一覧を 1 回だけ書く）。月表示は :has() で年表示のセルを除く。
    private static string MonthlyOrWeeklyIs(IEnumerable<DateOnly> dates) => $"{Standard} td.container:is(.is-weekly, :has(> div > .day):not(.other-month)){StandardIs(dates)}";

    private static string WeeklyCell(DateOnly date) => $"{Standard} td.container.is-weekly{DataId(date)}";

    /// <summary>CSS 文字列リテラル（二重引用符）用のエスケープ。制御文字は空白、非 ASCII はそのまま残す。</summary>
    public static string EscapeString(string value)
    {
        var escaped = new StringBuilder();
        foreach (var c in value)
        {
            if (c is '"' or '\\')
            {
                escaped.Append('\\').Append(c);
            }
            else if (c is '<' or '>' or '&')
            {
                escaped.Append('\\').Append(((int)c).ToString("x", CultureInfo.InvariantCulture)).Append(' ');
            }
            else if (char.IsControl(c))
            {
                escaped.Append(' ');
            }
            else
            {
                escaped.Append(c);
            }
        }
        return escaped.ToString();
    }
}
