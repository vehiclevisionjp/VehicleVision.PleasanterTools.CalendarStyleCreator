using System.Globalization;
using System.Text;

namespace VehicleVision.PleasanterTools.CalendarStyleCreator;

/// <summary>
/// 休日から拡張スタイル用 CSS を作る。同じ入力から常に同じ出力（日付順・重複日は後勝ち）。
/// セレクターは月表示の日セル <c>td.container[data-id="yyyy/M/d"]</c>（0 埋めなし）。
/// 本体の HtmlCalendar.cs で確認済み。画面での見え方は実機で未検証（_development/検証記録.md）。
/// </summary>
public static class CssGenerator
{
    private const string Scope = "#Calendar td.container";

    public static string Generate(IEnumerable<Holiday> holidays)
    {
        var byDate = new SortedDictionary<DateOnly, string>();
        foreach (var holiday in holidays) byDate[holiday.Date] = holiday.Name;
        var css = new StringBuilder();
        css.Append("/* Generated by CalendarStyleCreator. Do not edit. */\n");
        foreach (var (date, name) in byDate)
        {
            var selector = $"{Scope}[data-id=\"{date.Year}/{date.Month}/{date.Day}\"]";
            css.Append(CultureInfo.InvariantCulture, $"{selector} {{ background-color: #fff0f0; }}\n");
            css.Append(CultureInfo.InvariantCulture, $"{selector} .day {{ color: #d32f2f; }}\n");
            if (name.Length > 0)
                css.Append(CultureInfo.InvariantCulture, $"{selector} .day::after {{ content: \" {EscapeString(name)}\"; font-size: 0.8em; }}\n");
        }
        return css.ToString();
    }

    /// <summary>CSS 文字列リテラル（二重引用符）用のエスケープ。制御文字は空白、非 ASCII はそのまま残す。</summary>
    public static string EscapeString(string value)
    {
        var escaped = new StringBuilder();
        foreach (var c in value)
        {
            if (c is '"' or '\\') escaped.Append('\\').Append(c);
            else if (c is '<' or '>' or '&') escaped.Append('\\').Append(((int)c).ToString("x", CultureInfo.InvariantCulture)).Append(' ');
            else if (char.IsControl(c)) escaped.Append(' ');
            else escaped.Append(c);
        }
        return escaped.ToString();
    }
}
